/** 설명 표에 있는 모든 코드(시험이 엔진의 코드와 대조한다) */
export const KNOWN_CODES: readonly string[] = Object.keys(TABLE);

/** 표에 없는 코드에 붙이는 일반 설명 */
export const UNKNOWN_EXPLANATION = "자세한 설명이 아직 없는 문제입니다.";

/** 코드에 맞는 쉬운 말 한 문장. 모르는 코드(또는 코드가 아닌 값)는 코드와 일반 설명으로 낸다. */
export function plainOf(code: unknown): string {
  if (typeof code === "string" && Object.hasOwn(TABLE, code)) return TABLE[code] as string;
  const shown = typeof code === "string" && code !== "" ? code.replace(/[\u0000-\u001f\u007f]/g, "").slice(0, 64) : "(코드 없음)";
  return `${shown}: ${UNKNOWN_EXPLANATION}`;
}
